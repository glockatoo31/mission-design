// Balance test: streams every part type at several sizes (192,000 designs per contract) through the same model code the app uses, for each contract and its round-2 amendment,
// and checks the tuning targets.
// Run: npm run balance          (about two minutes)
//      npm run balance -- --write-par   regenerates src/par.js (the stored cheapest designs), then run it again
import { writeFileSync } from 'node:fs';
import { CONTRACTS, DESTINATIONS, STEPS } from '../src/data.js';
import { simulate, designGrid, NOMINAL, ESTIMATE, budgets, budgetMargins, par, mulberry32 } from '../src/model.js';
import { interfaces, failRow } from '../src/syseng.js';
import { trade, decisions } from '../src/trades.js';
import { PAGES, challengeState } from '../src/pages.js';

const writePar = process.argv.includes('--write-par');
const pct = (n, d) => `${((100 * n) / d).toFixed(1)}%`;
const checks = [];
const check = (ok, msg) => { checks.push({ ok, msg }); };
const KEYS = ['massMargin', 'dvMargin', 'powerMargin', 'dataMargin', 'thermalMargin', 'radMargin', 'costMargin', 'lifeMargin', 'timeMargin', 'flybyMargin', 'hazardMargin'];
const minMargin = (d) => Math.min(...Object.values(budgetMargins(budgets(d, ESTIMATE))).filter((m) => typeof m === 'number'));
const optWins = Object.fromEntries(STEPS.map((s) => [s.key, Object.fromEntries(s.list.map((o) => [o.id, 0]))]));
let totalWins = 0;

// One streaming pass over a contract's whole design space.
const rng = mulberry32(12345);
function sweep(C, changed) {
  const S = { overBudget: 0, n: 0, full: 0, min: 0, modes: {}, traj: { direct: 0, assist: 0 }, passes: Object.fromEntries(KEYS.map((k) => [k, 0])), best: null, bestThin: -1, allGreen: 0, samples: [], csamples: [] };
  for (const d of designGrid(C.id, changed)) {
    const r = simulate(d, NOMINAL); S.n++;
    if (r.outcome === 'full') {
      S.full++; S.traj[d.traj]++;
      if (!S.best || r.cost < S.best.cost) S.best = { d, cost: r.cost };
      S.bestThin = Math.max(S.bestThin, minMargin(d));
      { totalWins++; for (const s of STEPS) optWins[s.key][d[s.key]]++; }
    } else if (r.outcome === 'min') S.min++;
    // Failure modes are the physical ones: a design that is also over budget is re-flown with the bailout
    // so that cost does not hide what would actually go wrong.
    if (r.failure) {
      const phys = r.failure.mode === 'cost' ? simulate(d, { ...NOMINAL, bailout: true }).failure : r.failure;
      if (r.failure.mode === 'cost') S.overBudget++;
      if (phys) S.modes[phys.mode] = (S.modes[phys.mode] || 0) + 1;
    }
    for (const k of KEYS) { const m = r.b[k]; if (m === 'na' || m >= 0) S.passes[k]++; }
    // nobody should be able to make every bar green; cost margin is unaffected by growth, so test it first
    if (r.b.costMargin >= 0.15 && minMargin(d) >= 0.15) S.allGreen++;
    if (!changed) { const u = rng(); if (u < 1 / 997) S.samples.push(d); if (u < 1 / 1999) S.csamples.push(d); }
  }
  return S;
}

const seenGlobal = Object.fromEntries(PAGES.map((p) => [p.key, new Set()]));
const base = {};
for (const C of CONTRACTS) {
  const t0 = Date.now();
  base[C.id] = sweep(C, false);
  console.log(`swept ${C.name} (${base[C.id].n} designs) in ${((Date.now() - t0) / 1000).toFixed(0)}s`);
}

// --write-par: store the cheapest designs for the app (par cost, and the debug "cheapest" button).
if (writePar) {
  const out = {};
  for (const C of CONTRACTS) {
    out[C.id] = {
      base: { cost: Math.round(base[C.id].best.cost), design: base[C.id].best.d },
    };
  }
  writeFileSync(new URL('../src/par.js', import.meta.url), `// Generated by \`npm run balance -- --write-par\`. The cheapest full-success design for each contract\n// (the same contract in all three rounds). The balance test fails if this is out of date.\nexport const PAR = ${JSON.stringify(out, null, 1)};\n`);
  console.log('\nWrote src/par.js. Run `npm run balance` again to check it.');
  process.exit(0);
}

for (const C of CONTRACTS) {
  const D = DESTINATIONS.find((x) => x.id === C.dest);
  const S = base[C.id];
  const rate = S.full / S.n;

  console.log(`\n=== ${C.name} (${D.name}, x${D.mult}) - ${S.n} designs ===`);
  console.log(`Deadline ${C.deadline} yr, funding $${C.budget}M, goal ${C.goalGb} Gbit with ${C.payload}`);
  console.log(`Full success: ${S.full} (${pct(S.full, S.n)})   Minimum: ${S.min} (${pct(S.min, S.n)})   Direct ${S.traj.direct} / Assist ${S.traj.assist}`);
  console.log('Failure modes (first failure): ' + Object.entries(S.modes).sort((a, b) => b[1] - a[1]).map(([m, c]) => `${m} ${pct(c, S.n)}`).join(', '));
  console.log('Each constraint alone passes: ' + KEYS.map((k) => `${k.replace('Margin', '')} ${pct(S.passes[k], S.n)}`).join(', '));
  if (S.best) console.log(`Cheapest full success: $${Math.round(S.best.cost)}M of $${C.budget}M; thinnest nominal margin of any winner ${(S.bestThin * 100).toFixed(1)}%`);

  // Funding is set from par; the stored par.js must match the solver.
  check(!!S.best, `${C.name}: has a full-success design`);
  if (S.best) {
    const parMargin = (C.budget - S.best.cost) / C.budget;
    check(parMargin >= 0.1 && parMargin <= 0.14, `${C.name}: funding keeps par ($${Math.round(S.best.cost)}M) at ${(parMargin * 100).toFixed(0)}% cost margin (want 10-14%)`);
    check(par(C.id) === Math.round(S.best.cost), `${C.name}: par.js matches the solver ($${par(C.id)}M)`);
    const rows = interfaces(S.best.d); const bad = rows.filter((r) => r.margin != null && r.margin < 0).map((r) => r.label);
    check(bad.length === 0, `${C.name}: cheapest winner meets every interface requirement${bad.length ? ` (fails ${bad.join(', ')})` : ` (${rows.length} rows)`}`);
    const miss = PAGES.filter((p) => !challengeState(p, S.best.d).met).map((p) => p.key);
    check(miss.length === 0, `${C.name}: cheapest winner meets all ${PAGES.length} mini-challenges${miss.length ? ` (misses ${miss.join(', ')})` : ''}`);
  }
  check(S.full >= 5 && rate <= 0.35, `${C.name}: ${S.full} winning designs (>=5), ${pct(S.full, S.n)} of all (<=35%)`);
  check(S.allGreen === 0, `${C.name}: no design has every bar green (${S.allGreen} do)`);
  check(S.bestThin >= 0.05 && S.bestThin < 0.15, `${C.name}: best winning design runs ${(S.bestThin * 100).toFixed(1)}% thin (want 5-14%)`);
  check(Object.keys(S.modes).length >= 3, `${C.name}: ${Object.keys(S.modes).length} failure modes reachable (>=3)`);
  const hazardMode = { mercury: 'overheat', mars: 'storm', europa: 'radiation', pluto: 'data' }[D.id];
  check(!!S.modes[hazardMode], `${C.name}: its hazard (${hazardMode}) is the first failure of some design`);
  for (const key of ['direct', 'assist']) {
    const fast = D.traj[key].cruise <= C.deadline;
    if (fast) check(S.traj[key] > 0, `${C.name}: ${key} meets the ${C.deadline} yr deadline and has a winning design (${S.traj[key]})`);
    else check(!!S.modes.deadline, `${C.name}: ${key} (${D.traj[key].cruise} yr) misses the deadline and is catchable (deadline failures ${S.modes.deadline || 0})`);
  }

  // Sampled designs: mini-challenges, trades, decision record, interfaces.
  for (const d of [...S.csamples, ...(S.best ? [S.best.d] : [])]) for (const p of PAGES) { const s = challengeState(p, d); seenGlobal[p.key].add(s.met ? (s.lean ? 'lean' : 'over') : 'unmet'); }

  const dominant = [];
  for (const traj of ['direct', 'assist']) for (const s of STEPS) {
    const t = trade(s.key, { ...S.samples[0], traj });
    for (const o of t.options) if (t.criteria.every((c) => t.isBest(o, c))) dominant.push(`${s.key}:${o.id}`);
  }
  check(dominant.length === 0, `${C.name}: every choice is a real trade (${dominant.length ? 'dominant ' + dominant.join(', ') : 'no option best on every criterion'})`);
  let broken = 0; for (const d of S.samples) { try { decisions({ ...d, why: {} }).forEach((x) => { if (!x.option || !(x.gaps.length >= 0)) broken++; }); } catch { broken++; } }
  check(broken === 0, `${C.name}: the decision record works for sampled designs (${broken} errors)`);

  let drift = 0; let traced = 0; let tracedOk = 0;
  for (const d of S.samples) {
    const rows = interfaces(d);
    for (const label of ['Power', 'Heat', 'Lift', 'Cost']) {
      const r = rows.find((x) => x.label === label); if (!r) continue;
      if (Math.abs(r.sources.reduce((s, x) => s + x.v, 0) - r.need) > 0.01 * Math.max(1, r.need)) drift++;
    }
    const f = simulate(d, ESTIMATE).failure;
    const lab = f && !f.partial && !['night', 'storm', 'life', 'deadline'].includes(f.mode) ? failRow(f, budgets(d, ESTIMATE)) : null;
    const row = lab && rows.find((x) => x.label === lab);
    if (row && row.margin != null) { traced++; if (row.margin < 0) tracedOk++; }
  }
  check(drift === 0, `${C.name}: interface demands add up to the need (${drift} mismatches)`);
  check(traced === 0 || tracedOk / traced >= 0.98, `${C.name}: failures trace to the interface in deficit (${tracedOk}/${traced})`);
}

// Mini-challenges are real tests: across the sampled designs each one lands in at least two different
// outcomes (not met, met but over-built, met and lean), so choosing well always matters.
for (const p of PAGES) check(seenGlobal[p.key].size >= 2, `${p.title}: the mini-challenge has at least two possible outcomes (${[...seenGlobal[p.key]].join(', ')})`);

// Across all contracts: no part is in every winner, and every part wins somewhere (none is dead weight).
for (const s of STEPS) for (const o of s.list) {
  const c = optWins[s.key][o.id];
  check(c < totalWins, `${s.key}: ${o.name} is not in every successful design (${c}/${totalWins})`);
  check(c > 0, `${s.key}: ${o.name} is in at least one successful design (${c})`);
}

// Attempt-1 bailout: an over-budget design flies instead of being cancelled at program review.
{
  let d = null;
  for (const x of designGrid(CONTRACTS[0].id)) if (simulate(x, NOMINAL).failure?.mode === 'cost') { d = x; break; }
  const flown = simulate(d, { ...NOMINAL, bailout: true });
  check(flown.failure?.mode !== 'cost', `Bailout: over-budget design flies on attempt 1 (${flown.outcome}${flown.failure ? `, ${flown.failure.mode}` : ''})`);
}

console.log('\n=== Checks ===');
for (const c of checks) console.log(`${c.ok ? 'PASS' : 'FAIL'}  ${c.msg}`);
const failed = checks.filter((c) => !c.ok).length;
console.log(failed ? `\n${failed} check(s) failed.` : '\nAll checks passed.');
process.exitCode = failed ? 1 : 0;
